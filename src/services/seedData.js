const fence = (src, lang = 'text') => '```' + lang + '\n' + src + '\n```';
const bullets = (items) => items.map((x) => `- ${x}`).join('\n');
const steps = (items) => items.map((x, i) => `${i + 1}. ${x}`).join('\n');

/**
 * Builds a task context in the same shape as CONTEXT_TEMPLATE (services/promptFormat.js):
 * Resources for the agent, then a REASONS canvas (Structured Prompt-Driven Development).
 */
function spdd({
  logs, stack, code, codeLang = 'js', files = [],
  problem, done, entities = [], approach = [], structure = [], operations = [], norms = [], safeguards = [],
}) {
  const out = ['## Resources'];
  if (logs) out.push('### Logs', fence(logs));
  if (stack) out.push('### Stack trace', fence(stack));
  if (code) out.push('### Code', fence(code, codeLang));
  if (files.length) out.push('### Relevant files & docs', bullets(files));

  out.push('## REASONS Canvas (SPDD)', '### R — Requirements', `Problem: ${problem}\nDefinition of Done: ${done}`);
  if (entities.length) out.push('### E — Entities', bullets(entities));
  if (approach.length) out.push('### A — Approach', bullets(approach));
  if (structure.length) out.push('### S — Structure', bullets(structure));
  if (operations.length) out.push('### O — Operations', steps(operations));
  if (norms.length) out.push('### N — Norms', bullets(norms));
  if (safeguards.length) out.push('### S — Safeguards', bullets(safeguards));
  return out.join('\n\n');
}

